// Each byte lane holds eight samples: end/midpoint anchors, then progressively
// finer midpoint residuals; newer families store absolute leaves.
inline bool decode_half(const uint8_t *data, int bytes, int lane, int h, int previous, int16_t *out)
{
	if (h >= 0xf8 && bytes < 2)
	{
		return false;
	}
	const int prefix = (h < 0xc0) ? 2 : (h < 0xe0) ? 3 : 4;
	int anchor, middle, quarter, leaf, shift;
	if (h < 0x4c)
	{
		anchor = bytes + 1;
		middle = bytes + 1;
		quarter = bytes;
		leaf = bytes - 1;
		shift = ((h >> 4) & 12) + ((h >> 2) & 3) + 9 - bytes;
	}
	else if (h < 0xc0)
	{
		anchor = bytes + 5;
		middle = bytes + 1;
		quarter = bytes;
		leaf = bytes - 2;
		shift = ((h >> 4) & 12) + ((h >> 2) & 3) - bytes;
	}
	else if (h == 0xc0)
	{
		anchor = bytes + 4;
		middle = bytes + 1;
		quarter = bytes;
		leaf = bytes - 2;
		shift = 12 - bytes;
	}
	else if (h < 0xd0)
	{
		anchor = bytes + 3;
		middle = bytes + 2;
		quarter = bytes;
		leaf = bytes - 2;
		shift = ((h & 14) >> 1) + 7 - bytes;
	}
	else if (h == 0xe5 || h == 0xe7 || h == 0xe8 || h == 0xe9)
	{
		anchor = bytes + 3;
		middle = bytes - 1;
		quarter = bytes - 1;
		leaf = bytes - 1;
		shift = ((h == 0xe5) ? 1 : (h - 0xe5)) - bytes;
	}
	else if (h == 0xea || h == 0xeb)
	{
		anchor = bytes + 2;
		middle = bytes;
		quarter = bytes - 1;
		leaf = bytes - 1;
		shift = h - 0xea + 6 - bytes;
	}
	else if (h >= 0xec && h <= 0xf0)
	{
		anchor = bytes + 6;
		middle = bytes;
		quarter = bytes - 1;
		leaf = bytes - 2;
		shift = h - 0xee + 8 - bytes;
	}
	else if (h >= 0xf1 && h <= 0xfe)
	{
		anchor = bytes;
		middle = bytes;
		quarter = bytes;
		leaf = bytes - 1;
		shift = h - ((h >= 0xf8) ? 0xf8 : 0xf1) + 10 - bytes;
	}
	else
	{
		return false;
	}
	if (bytes > 8 || std::min({ anchor, middle, quarter, leaf }) < 0
		|| prefix + anchor + middle + 2 * quarter + 4 * leaf != 8 * bytes)
	{
		return false;
	}

	uint64_t raw = 0;
	for (int i = 0; i < bytes; ++i)
	{
		raw = (raw << 8) | data[2 * i + lane];
	}
	const int widths[8] = { anchor, middle, quarter, quarter, leaf, leaf, leaf, leaf };
	int position = prefix;
	double field[8]{};
	for (int i = 0; i < 8; ++i)
	{
		const int width = widths[i];
		if (!width)
		{
			continue;
		}
		int64_t value = (raw >> (8 * bytes - position - width)) & ((uint64_t(1) << width) - 1);
		if (value & (int64_t(1) << (width - 1)))
		{
			value -= int64_t(1) << width;
		}
		position += width;
		const int scale = shift + ((h >= 0xf8 && i >= 4) ? 1 : 0);
		field[i] = std::ldexp(double(value), scale);
		if (scale > 0)
		{
			field[i] += std::ldexp(1.0, scale - 1);
			if (i == 0 || (i == 1 && (h < 0x4c || h == 0xce || h >= 0xf1))
				|| ((i == 2 || i == 3) && h >= 0xf1) || h >= 0xf8)
			{
				field[i] -= 1;
			}
		}
	}

	auto average = [] (double x, double y) { return std::floor((x + y) / 2); };
	double sample[8]{};
	sample[7] = std::floor(field[0]);
	if (h == 0xce)
	{
		const int value = int(sample[7]);
		sample[7] = ((value + 32768) % 65536 + 65536) % 65536 - 32768;
	}
	sample[3] = (h < 0x4c || h == 0xce || h >= 0xf1) ? std::floor(field[1]) : (average(previous, sample[7]) + field[1]);
	sample[1] = (h >= 0xf1) ? std::floor(field[2]) : (average(previous, sample[3]) + field[2]);
	sample[5] = (h >= 0xf1) ? std::floor(field[3]) : (average(sample[3], sample[7]) + field[3]);
	sample[0] = (h >= 0xf8) ? field[4] : (average(previous, sample[1]) + field[4]);
	sample[2] = (h >= 0xf8) ? field[5] : (average(sample[1], sample[3]) + field[5]);
	sample[4] = (h >= 0xf8) ? field[6] : (average(sample[3], sample[5]) + field[6]);
	sample[6] = (h >= 0xf8) ? field[7] : (average(sample[5], sample[7]) + field[7]);
	for (int i = 0; i < 8; ++i)
	{
		out[i] = int16_t(std::clamp(std::floor(sample[i]), -32768.0, 32767.0));
	}
	return true;
}

inline unsigned header(const uint8_t *data)
{
	const unsigned h = (data[1] & 0xf0) | (data[0] >> 4);
	return h & ((h < 0xc0) ? 0xcc : (h < 0xe0) ? 0xee : 0xff);
}

inline uint32_t read32(const uint8_t *p)
{
	return uint32_t(p[0]) | (uint32_t(p[1]) << 8) | (uint32_t(p[2]) << 16) | (uint32_t(p[3]) << 24);
}

inline uint16_t read16(const uint8_t *p)
{
	return p[0] | (p[1] << 8);
}

struct phrase
{
	uint32_t start = 0;
	uint32_t end = 0;
	uint32_t limit = 0;
	uint8_t table = 0;
	uint8_t channels = 0;
	uint8_t step = 0;
};

inline unsigned phrase_count(const uint8_t *rom, uint32_t size)
{
	if (size < 4 || read16(rom) != 0x490c)
	{
		return 0;
	}
	const unsigned end = read16(rom + 2) * 2;
	return (end >= 4 && end <= size && (end - 4) % 10 == 0) ? std::min((end - 4) / 10, 4096U) : 0;
}

inline bool describe(const uint8_t *rom, uint32_t size, unsigned number, phrase &p)
{
	const unsigned count = phrase_count(rom, size);
	if (number >= count)
	{
		return false;
	}
	const uint8_t *entry = rom + 4 + number * 10;
	const uint32_t start = read32(entry);
	const uint32_t end = read32(entry + 4);
	const unsigned format = read16(entry + 8);
	unsigned table = 0;
	for (; table < std::size(FORMATS); ++table)
	{
		if (FORMATS[table].format == (format & 0xff7f))
		{
			break;
		}
	}
	if (table == std::size(FORMATS))
	{
		return false;
	}

	// nominal rates validated against PSP/PS2 assets: 44.1 kHz * (tag + 1) / 8
	const unsigned tag = start & 15;
	if (tag != 2 && tag != 3 && tag != 4 && tag != 7)
	{
		return false;
	}
	p.start = (start >> 4) * 2;
	p.end = (end >> 4) * 2;
	p.limit = (number + 1 < count) ? ((read32(entry + 10) >> 4) * 2) : size;
	p.table = table;
	p.channels = (format & 0x80) ? 2 : 1;
	p.step = tag + 1;
	if ((end & 15) != 15 || p.start < read16(rom + 2) * 2U || p.start > p.end || p.limit > size || p.end + 2 > p.limit)
	{
		return false;
	}
	const unsigned length = FORMATS[table].length[header(rom + p.end)];
	return length >= 2 && p.end + length <= p.limit;
}

// At most sixteen native frames are buffered.  FF runs are counted per channel:
// stereo blocks are interleaved by expanded time, not alternation.
struct decoder
{
	uint32_t cursor = 0;
	uint32_t end = 0;
	uint32_t limit = 0;
	uint16_t silence[2]{};
	int16_t previous[2]{};
	int16_t pcm[2][16]{};
	uint8_t table = 0;
	uint8_t channels = 0;
	uint8_t index = 16;
	bool failed = false;

	void start(const phrase &p)
	{
		*this = decoder();
		cursor = p.start;
		end = p.end;
		limit = p.limit;
		table = p.table;
		channels = p.channels;
	}

	bool frame(const uint8_t *rom, int16_t *out)
	{
		if (failed)
		{
			return false;
		}
		if (index == 16)
		{
			if (cursor > end && !silence[0] && !silence[1])
			{
				return false;
			}
			for (unsigned ch = 0; ch < channels; ++ch)
			{
				if (silence[ch])
				{
					--silence[ch];
					std::fill(std::begin(pcm[ch]), std::end(pcm[ch]), 0);
					continue;
				}
				if (cursor > end || cursor + 2 > limit)
				{
					failed = true;
					return false;
				}
				const uint8_t *data = rom + cursor;
				const unsigned h = header(data);
				const unsigned length = FORMATS[table].length[h];
				if (length < 2 || (length & 1) || cursor + length > limit)
				{
					failed = true;
					return false;
				}
				if (h == 0xff)
				{
					const unsigned word = read16(data);
					silence[ch] = ((word >> 4) & 0xf0) | (word & 15);
					std::fill(std::begin(pcm[ch]), std::end(pcm[ch]), 0);
				}
				else if (!decode_half(data, length / 2, 1, h, previous[ch], pcm[ch]) || !decode_half(data, length / 2, 0, h, pcm[ch][7], pcm[ch] + 8))
				{
					failed = true;
					return false;
				}
				previous[ch] = pcm[ch][15];
				cursor += length;
			}
			index = 0;
		}
		out[0] = pcm[0][index];
		out[1] = (channels == 2) ? pcm[1][index] : 0;
		++index;
		return true;
	}
};

