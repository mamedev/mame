/**********************************************************************

    Nokia MikroMikko 2 CRTC186 emulation

    The video is generated by a CRT9007 VPAC that loads a data row into
    a pair of CRT9212 double row buffers, one for the character codes
    and one for the attributes. The character generator EPROM (IC40) is
    addressed by the character code and the scan line address, and the
    dot pattern it outputs is fed through the attribute EPROM (IC26),
    which takes the place of the CRT9021 VAC found on similar designs.

    The attribute EPROM address lines are:

        A0-A7   dot data from the character generator
        A8      BLDL, i.e. dot data ORed with itself delayed by one dot
        A9      NONE, i.e. the background level is output
        A10     REVL, i.e. the dot data is complemented
        A11     LNEL, the dot shifted in on the graphics mode path
        A12     MODEG, graphics mode

    The dot data is always output in reverse bit order, i.e. the LSB of
    the character generator data is the leftmost dot of the character.

    The dot pattern is only 8 dots wide, so the first and the last dot
    of the 10 dot character time are filled outside the attribute EPROM.
    The underline attribute and the underline cursor are not inputs to
    the attribute EPROM either, but light up the whole character time of
    the last scan line of the data row.

*********************************************************************/

