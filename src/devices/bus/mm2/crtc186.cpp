void crtc186_device::vidla_w(uint8_t data)
{
	m_vidla = data;

	m_dout = true;
}

void crtc186_device::drb_attr_w(uint8_t data)
{
	/*

	    bit     description

	    0       character generator A12
	    1       LNEL, line graphics
	    2       REVL, reverse video
	    3       half lit background
	    4       NONE, blank
	    5       BLDL, bold
	    6       UNDL, underline
	    7       blinking character

	*/

	m_vidat = data;
}

void crtc186_device::set_vidldsh_timer()
{
	const XTAL busdotclk = XTAL(35'452'500) / (m_mode ? 2 : 1);
	const XTAL vidcclk = busdotclk / character_width();

	m_vpac->set_character_width(character_width());
	m_vpac->set_unscaled_clock(vidcclk);

	// the character time is locked to the start of the scan line
	m_timer_vidldsh->adjust(m_screen->time_until_pos(0, 0), 0, attotime::from_hz(vidcclk));
}

void crtc186_device::draw_character(int x, int y)
{
	rectangle const &visarea = m_screen->visible_area();

	if ((y < visarea.top()) || (y > visarea.bottom()) || (x < visarea.left()) || ((x + character_width() - 1) > visarea.right()))
		return;

	if (!m_blc)
	{
		// the video output is turned off
		for (int dot = 0; dot < character_width(); dot++)
			m_bitmap.pix(y, x + dot) = rgb_t::black();

		return;
	}

	// character generator
	offs_t const char_addr = (BIT(m_vidat, 0) << 12) | (m_vidla << 4) | m_cgra;
	u8 const vidd = m_char_rom->base()[char_addr & 0x1fff];

	// the cursor and the blinking characters blink at 2 Hz
	bool const blink = !BIT(machine().time().as_ticks(4), 0);

	// attributes
	bool const lnel = BIT(m_vidat, 1);
	bool const revl = BIT(m_vidat, 2);
	bool const half = BIT(m_vidat, 3);
	bool const bldl = BIT(m_vidat, 5);
	bool const undl = BIT(m_vidat, 6);
	bool const blnk = BIT(m_vidat, 7);

	// a blinking character outputs the background level for half of the time
	bool const none = BIT(m_vidat, 4) || (blnk && !blink);

	// attribute PROM
	offs_t const attr_addr = (m_modeg << 12) | (lnel << 11) | (revl << 10) | (none << 9) | (bldl << 8) | vidd;
	u8 const video = m_attr_rom->base()[attr_addr];

	// the PROM output for an empty dot pattern is the background level of the
	// character, and the one without the bold attribute has the last dot of the
	// character in bit 0
	u8 const background = m_attr_rom->base()[attr_addr & ~0xff];
	u8 const unbold = m_attr_rom->base()[attr_addr & ~0x100];

	// the dot pattern is only 8 dots wide, so the first and the last dot of the
	// character are filled with the background level, except that line graphics
	// characters repeat the first and the last dot of the pattern to join them to
	// the neighbouring characters, and bold characters extend their last dot
	bool const first = lnel ? bool(BIT(video, 7)) : bool(BIT(background, 7));
	bool const last = lnel ? bool(BIT(video, 0)) : (bldl ? bool(BIT(unbold, 0)) : bool(BIT(background, 0)));

	// the control latch inhibits the blinking of the cursor
	bool const cursor = (m_crb || blink) && m_vpac->cursor_active(m_col, m_row);

	// the underline attribute and the underline cursor light up the whole
	// character time of the last scan line of the data row
	bool const underline = (m_cgra == 14) && (undl || (cursor && m_cru));

	// the reverse video cursor complements the video output
	bool const invert = m_cpl ^ (cursor && !m_cru);

	rgb_t const bgcolor = half ? halflit() : rgb_t::white();

	for (int dot = 0; dot < character_width(); dot++)
	{
		// the dot pattern is loaded into the shift register one dot into the
		// character time
		bool pixel = (dot == 0) ? first : ((dot < 9) ? bool(BIT(video, 8 - dot)) : last);

		if (underline)
			pixel = true;

		m_bitmap.pix(y, x + dot) = (pixel ^ invert) ? rgb_t::black() : bgcolor;
	}
}

TIMER_DEVICE_CALLBACK_MEMBER( crtc186_device::vidldsh_tick )
{
	// the character time is locked to the raster, so the first character time of
	// the scan line is the one at the start of the line
	int const x = m_screen->hpos();

	if (!x)
	{
		if (!m_drb)
		{
			// the row buffers are swapped for the first scan line of a new data row
			m_cgra = 0;

			if (m_frame)
			{
				// the first data row after the vertical retrace starts the picture
				m_frame = false;
				m_row = 0;
				m_scanline = 0;
			}
			else
			{
				m_row++;
				m_scanline++;
			}
		}
		else
		{
			// a new scan line advances the character generator row address
			m_cgra = (m_cgra + 1) & 0x0f;
			m_scanline++;
		}
	}

	m_drb0->rclk_w(0);
	m_drb0->wclk_w(0);
	m_drb1->rclk_w(0);
	m_drb1->wclk_w(0);

	m_dout = false;

	m_drb0->rclk_w(1);
	m_drb0->wclk_w(1);
	m_drb1->rclk_w(1);
	m_drb1->wclk_w(1);

	if (m_dout)
	{
		// the row buffer outputs one character for each character time of the
		// visible line time
		draw_character(m_col * character_width(), m_scanline);

		m_col++;
	}
	else
	{
		// the read address counter is cleared outside of the visible line time
		m_col = 0;
	}
}
