/**********************************************************************

    Tandy Model 12/16B/6000 low-profile Keytronic keyboard emulation

    Keytronic 8790522, schematic 8000196 (Project 448)

    TODO:

    - Bottom-row key positions (space, KP0, KP., KP ENTER on Keytronic
      positions 78-87) are inferred from the row-major numbering and
      not confirmed.
    - Z2 sense output polarity at P1 is not shown; active low assumed.
    - Which PROG edge latches the Z3 column and re-arms Z2 is unknown;
      the capacitive sense timing is not modelled.
    - German layout (T1 = 1) keycap legends are unknown.

**********************************************************************/

