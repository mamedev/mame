const tiny_rom_entry *tandy6k_keyboard_device::device_rom_region() const
{
	return ROM_NAME( tandy6k_kbd );
}


void tandy6k_keyboard_device::device_add_mconfig(machine_config &config)
{
	I8048(config, m_maincpu, 3.579545_MHz_XTAL);
	m_maincpu->t0_in_cb().set(FUNC(tandy6k_keyboard_device::t0_r));
	m_maincpu->t1_in_cb().set(FUNC(tandy6k_keyboard_device::t1_r));
	m_maincpu->p1_in_cb().set(FUNC(tandy6k_keyboard_device::p1_r));
	m_maincpu->p1_out_cb().set(FUNC(tandy6k_keyboard_device::p1_w));
	m_maincpu->p2_out_cb().set(FUNC(tandy6k_keyboard_device::p2_w));
	m_maincpu->prog_out_cb().set(FUNC(tandy6k_keyboard_device::prog_w));
}


