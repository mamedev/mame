ioport_constructor tandy6k_keyboard_device::device_input_ports() const
{
	return INPUT_PORTS_NAME( tandy6k_kbd );
}


tandy6k_keyboard_device::tandy6k_keyboard_device(const machine_config &mconfig, const char *tag, device_t *owner, uint32_t clock) :
	device_t(mconfig, TANDY6K_KEYBOARD, tag, owner, clock),
	device_trs80m2_keyboard_interface(mconfig, *this),
	m_maincpu(*this, "z4"),
	m_col(*this, "C%u", 0U),
	m_layout(*this, "E6"),
	m_leds(*this, "led%u", 0U),
	m_p1(0xff),
	m_column(0),
	m_prog(1),
	m_busy(1),
	m_data(0),
	m_clk(0)
{
}

void tandy6k_keyboard_device::device_start()
{
	save_item(NAME(m_p1));
	save_item(NAME(m_column));
	save_item(NAME(m_prog));
	save_item(NAME(m_busy));
	save_item(NAME(m_data));
	save_item(NAME(m_clk));
}

int tandy6k_keyboard_device::data_r()
{
	return m_data;
}

void tandy6k_keyboard_device::busy_w(int state)
{
	m_busy = state;
}

int tandy6k_keyboard_device::t0_r()
{
	return m_busy;
}

int tandy6k_keyboard_device::t1_r()
{
	return BIT(m_layout->read(), 0);
}

uint8_t tandy6k_keyboard_device::p1_r()
{
	return (m_column < 12) ? m_col[m_column]->read() : 0xff;
}

void tandy6k_keyboard_device::p1_w(uint8_t data)
{
	m_p1 = data;
}

void tandy6k_keyboard_device::p2_w(uint8_t data)
{
	int const data_bit = !BIT(data, 7);
	int const clk = !BIT(data, 6);

	if (m_data != data_bit || m_clk != clk)
	{
		m_data = data_bit;
		m_clk = clk;

		m_port->clock_w(clk);
	}

	m_leds[0] = BIT(data, 5);
	m_leds[1] = BIT(data, 4);
}

void tandy6k_keyboard_device::prog_w(int state)
{
	if (m_prog && !state)
		m_column = m_p1 & 0x0f;

	m_prog = state;
}
