void kb305_device::device_add_mconfig(machine_config &config)
{
	I8049(config, m_mcu, 6_MHz_XTAL);
	m_mcu->set_addrmap(AS_PROGRAM, &kb305_device::program_map);
	m_mcu->bus_in_cb().set(FUNC(kb305_device::bus_r));
	m_mcu->p1_out_cb().set(FUNC(kb305_device::p1_w));
	m_mcu->p2_in_cb().set_ioport("P2");
	m_mcu->t0_in_cb().set(FUNC(kb305_device::t0_r));
	m_mcu->t1_in_cb().set(FUNC(kb305_device::t1_r));
}

const tiny_rom_entry *kb305_device::device_rom_region() const
{
	return ROM_NAME(kb305);
}

kb305_device::kb305_device(const machine_config &mconfig, const char *tag, device_t *owner, u32 clock) :
	adb_device_interface(mconfig, ADB_KB305, tag, owner, clock)
	, adb_slot_card_interface(mconfig, *this, DEVICE_SELF)
	, m_mcu(*this, "mcu")
	, m_rows{ *this, "ROW%u", 0U }
	, m_p2(*this, "P2")
	, m_t0(*this, "T0")
{
}

void kb305_device::device_start()
{
	adb_device_interface::device_start();

	save_item(NAME(m_adb_state));
	save_item(NAME(m_kbd_row));
	save_item(NAME(m_our_last_adb_state));
}

void kb305_device::device_reset()
{
	adb_device_interface::device_reset();

	m_our_last_adb_state = 1;
	m_adb_state = 1;
	m_kbd_row = 0x0f;
}

void kb305_device::adb_w(int state)
{
	m_adb_state = state;
}

void kb305_device::program_map(address_map &map)
{
	map(0x0000, 0x07ff).rom().region("mcu", 0);
}

u8 kb305_device::bus_r()
{
	return m_rows[m_kbd_row]->read();
}

void kb305_device::p1_w(u8 data)
{
	m_kbd_row = data & 0xf;

	// scroll lock LED is bit 6
	// num lock LED is bit 5
	// caps lock LED is bit 4

	// ADB drive is through an inverting transistor
	int adb_state = (data >> 7) ^ 1;
	if (adb_state != m_our_last_adb_state)
	{
		adb_drive_w(adb_state);
		m_our_last_adb_state = adb_state;
		m_mcu->yield();
	}
}

int kb305_device::t0_r()
{
	return m_t0->read() & 1;
}

int kb305_device::t1_r()
{
	return m_adb_state & 1;
}

