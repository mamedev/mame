/*********************************************************************

    kb305.cpp
    Adesso model 305 ADB keyboard
    by R. Belmont

    Port 1: Bits 0-3: binary column-strobe index (0-15) latched by an
                      external 4-to-16 decoder into 16 column drive lines.
            Bit 4: Caps Lock LED
            Bit 5: Num Lock LED
            Bit 6: Scroll Lock LED
            Bit 7: ADB line driver out (open-drain)
    Port 2: Bit 0: Command
            Bit 1: Left Option
            Bit 2: Left Shift
            Bit 3: Left Control
            Bit 4: Power key (sends ADB 0x7F)
            Bit 5: Caps Lock
            Bit 6: Right Shift
            Bit 7: Right Control
    Bus:    8-bit matrix sense input for the currently strobed column
    T0:     Right Option key (active low)
    T1:     ADB in

	TODO: LED output support

*********************************************************************/

