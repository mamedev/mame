#include <cstdio>

#define CF  0x100
#define HF  0x200
#define DF  0x400

int dab[0x800];

int main(int ac, char **av)
{
	int i;

	for (i = 0; i < DF; i++) {
		int val = i & 0xff;
		int lowfix, highfix;
		int result;

		/* add/adc and sub/sbc are one rule with the sign of the
		   correction flipped:

		     - correct the low digit if a half carry came in or the
		       digit is out of BCD range;
		     - correct the high digit under the same test, applied to
		       the value the low correction just produced;
		     - the carry out is produced by the high-digit correction
		       alone.  A ripple out of the low digit does not set it,
		       and sub/sbc CAN generate a borrow the caller did not
		       supply (0x00 with H set corrects to 0x9a, carry out).

		   Verified entry for entry against a real Zilog Z8001. */
		lowfix = (i & HF) || (val & 0x0f) > 0x09;

		result = val;
		if (lowfix)
			result = (result + 0x06) & 0xff;
		highfix = (i & CF) || ((result >> 4) & 0x0f) > 0x09;
		if (highfix)
			result = (result + 0x60) & 0xff;
		dab[i] = (highfix ? CF : 0) | result;

		result = val;
		if (lowfix)
			result = (result - 0x06) & 0xff;
		highfix = (i & CF) || ((result >> 4) & 0x0f) > 0x09;
		if (highfix)
			result = (result - 0x60) & 0xff;
		dab[DF + i] = (highfix ? CF : 0) | result;
	}

	printf("// license:BSD-3-Clause\n");
	printf("// copyright-holders:Juergen Buchmueller,Ernesto Corvi\n");
	printf("/************************************************\n");
	printf(" * Result table for Z8000 DAB instruction\n");
	printf(" *\n");
	printf(" * Generated by makedab.cpp; the rule it encodes\n");
	printf(" * was measured on a real Z8001, all 2048 entries.\n");
	printf(" *\n");
	printf(" * bits    description\n");
	printf(" * ----------------------------------------------\n");
	printf(" * 0..7    destination value\n");
	printf(" * 8       carry flag before\n");
	printf(" * 9       half carry flag before\n");
	printf(" * 10      D flag (0 add/adc, 1 sub/sbc)\n");
	printf(" *\n");
	printf(" * result  description\n");
	printf(" * ----------------------------------------------\n");
	printf(" * 0..7    result value\n");
	printf(" * 8       carry flag after\n");
	printf(" ************************************************/\n");
	printf("static const uint16_t Z8000_dab[0x800] = {\n");
	for (i = 0; i < 0x800; i++) {
		if ((i & 0x3ff) == 0) {
			if (i & 0x400)
				printf("\t/* sub/sbc results */\n");
			else
				printf("\t/* add/adc results */\n");
		}
		if ((i & 7) == 0) printf("\t");
		printf("0x%03x,",dab[i]);
		if ((i & 7) == 7) printf("\n");
	}
	printf("};\n");

	return 0;
}
