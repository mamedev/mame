void mpf3kbd_device::device_add_mconfig(machine_config &config)
{
	I8035(config, m_kbdmcu, 3.579545_MHz_XTAL); // INS8035N-6
	m_kbdmcu->set_addrmap(AS_PROGRAM, &mpf3kbd_device::prog_map);
	m_kbdmcu->bus_in_cb().set(FUNC(mpf3kbd_device::key_matrix_r));
	m_kbdmcu->p1_out_cb().set(FUNC(mpf3kbd_device::p1_w));
	m_kbdmcu->t0_in_cb().set_ioport("MODIFIERS").bit(2);
	m_kbdmcu->t1_in_cb().set(FUNC(mpf3kbd_device::shift_r));
}

