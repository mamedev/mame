/*********************************************************************

    Multitech MPF-III 90-key detached keyboard

    The PB0 and PB1 keys (not given iconic symbols here) are placed
    together directly to the left of BREAK and RESET, above the
    IBM PC-style numeric keypad.

    The ALT key macros are interpreted by the host system, using
    special key codes with the eighth bit transmitted as zero. These
    codes are also sent for the twelve function keys and when
    Caps Lock is switched on (not off).

    Connector pin assignments (from Operation Manual):

        1       PB1
        2       +5V
        3       GND
        4       DATA
        5       CLOCK
        6       STROBE
        7       PB0
        8       RESET
        9       AKD

*********************************************************************/

