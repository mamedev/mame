/* classify a PC as one of the known protection subroutines */
static const char *primrage_pc_note(uint32_t pc)
{
	switch (pc)
	{
		/* protection code from 20f90 - 21000 */
		case 0x20f90: case 0x20f98: case 0x20fa0: case 0x20fba: return "20f90";
		case 0x20fcc: return "20f90-done";

		/* protection code from 27592 - 27664 */
		case 0x275bc: case 0x275cc: case 0x275d2: case 0x275d8:
		case 0x275de: case 0x275f6: case 0x2761e: case 0x2762e: return "27592";
		case 0x2763e: return "27592-done";

		/* protection code from 3d8dc - 3d95a */
		case 0x3d8f4: case 0x3d8fa: case 0x3d908: case 0x3d90e:
		case 0x3d932: case 0x3d938: case 0x3d93e: return "3d8dc";
		case 0x3d944: return "3d8dc-done";

		/* protection code from 437fa - 43860 */
		case 0x43814: case 0x4381c: case 0x43830: case 0x43838: case 0x43840: return "437fa";
		case 0x43848: return "437fa-done";

		default: return nullptr;
	}
}

