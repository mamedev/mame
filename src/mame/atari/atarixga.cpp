namespace {

constexpr uint16_t parity(uint16_t x)
{
	return std::popcount(x) & 1;
}

// Both existing key tables are generated by a seven-bit LFSR, starting at
// state 1 and XORing each state with 0x28 to obtain the encoded key. Only the
// feedback mask differs. States outside the 15..126-clock range retain the
// 14-clock result (the original tables' "identical twins"). This reproduces
// every existing table entry; physical counter wiring is not independently known.
constexpr std::array<uint8_t, 128> make_xga_clock_table(uint8_t feedback)
{
	std::array<uint8_t, 128> result;
	result.fill(14);
	uint8_t state = 1;
	for (unsigned clocks = 126; clocks >= 15; --clocks)
	{
		result[state ^ 0x28] = clocks;
		state = ((state << 1) | parity(state & feedback)) & 0x7f;
	}
	return result;
}

constexpr auto SPCLORDS_CLOCKS = make_xga_clock_table(0x53);
constexpr auto MOTOFREN_CLOCKS = make_xga_clock_table(0x6a);

uint8_t xga_clock_count(uint8_t key, std::array<uint8_t, 128> const &clocks = SPCLORDS_CLOCKS)
{
	// Only 128 internal keys. Fold the high-bit "twin" onto its seven-bit key.
	if (key & 0x80)
		key ^= 0xa8;
	return clocks[key];
}

uint16_t spclords_key_offset(offs_t index)
{
	offs_t const address = index * 2;
	return bitswap<12>(address, 12, 11, 10, 9, 6, 3, 5, 4, 1, 7, 2, 8) ^ 0x0b3;
}

// General form of the Space Lords-family LFSR. Unlike its C100-specific
// inverse-state/power-of-two shortcuts below, this also handles feedback
// masks with bit 14 clear (four of Primal Rage's five observed masks).
uint16_t xga_decipher(uint16_t ciphertext, uint16_t taps, unsigned clocks)
{
	// Zero is represented by the 17th power word. This follows Space Lords;
	// it has not been independently observed on T-MEK or Primal Rage hardware.
	uint16_t state = ciphertext ? ciphertext : 1;
	if (!ciphertext)
		--clocks;

	uint16_t previous = state;
	bool early = false;
	for (unsigned i = 0; i < clocks; ++i)
	{
		previous = state;
		state = (state << 1) | parity(state & taps);
		early |= (state == 1);
	}

	// Passing state 1 shortens the result by one clock; landing on it
	// at the final clock represents zero instead.
	if (!early)
		return state;
	return (state == 1) ? 0 : previous;
}

} // anonymous namespace


