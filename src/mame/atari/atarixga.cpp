uint16_t atari_136094_0072_device::decipher(uint8_t key, uint16_t ciphertext)
{
	// Equivalent to the former basis-word/exception implementation for all
	// 256 keys and 65536 ciphertexts, including zero and powers of two.
	return xga_decipher(ciphertext, 0x8016, xga_clock_count(key, MOTOFREN_CLOCKS));
}


/*************************************
 *
 *  Write/Read access
 *
 *************************************/

void atari_136094_0072_device::write(offs_t offset, uint32_t data, uint32_t mem_mask)
{
	switch (m_mode)
	{
		case FPGA_RESET:
		case FPGA_RESULT:
			return;

		case FPGA_SETKEY:
			/* Write table to FPGA SRAM. */
			if (ACCESSING_BITS_16_31)
				m_ram[offset << 1] = uint16_t(data >> 16);
			if (ACCESSING_BITS_0_15)
				m_ram[(offset << 1) + 1] = uint16_t(data & 0xffff);
			break;

		case FPGA_DECIPHER:
			/* Send Ciphertext to FPGA for decryption. */
			if (ACCESSING_BITS_16_31)
			{
				m_address = offset << 2;
				m_ciphertext = uint16_t(data >> 16);
			}
			if (ACCESSING_BITS_0_15)
			{
				m_address = (offset << 2) + 2;
				m_ciphertext = uint16_t(data & 0xffff);
			}
			break;
	}
}

uint32_t atari_136094_0072_device::read(offs_t offset, uint32_t mem_mask)
{
	fpga_mode new_mode = m_mode;
	switch (offset << 2)
	{
		case 0x0fc0:
			new_mode = FPGA_RESET;
			break;
		case 0x0010:
			new_mode = FPGA_SETKEY;
			break;
		case 0x0008:
			if (new_mode == FPGA_DECIPHER)
				new_mode = FPGA_RESULT;
			break;
		case 0x0020:
			new_mode = FPGA_DECIPHER;
			break;
	}
	if (!machine().side_effects_disabled())
		m_mode = new_mode;

	// All five ROM revisions poll bit 15 here before the 0008 read switches
	// to result access. Returning plaintext (or zero for another index)
	// during this phase makes the game's 20-iteration poll loop time out.
	// The result is computed immediately; physical busy timing is unknown.
	if (new_mode == FPGA_DECIPHER)
		return ((offset << 2) == 0x0400 && ACCESSING_BITS_16_31) ? 0x80000000 : 0;

	uint32_t plaintext = 0;
	if (new_mode == FPGA_RESULT)
	{
		uint16_t address = (offset << 2) - 0x400;

		if (ACCESSING_BITS_0_15)
			address += 2;

		/* Reply with decrypted plaintext */
		// The ROM masks the result address to nine bits. High query bits
		// still select the key, so use the latched write address for that.
		if (address == (m_address & 0x01ff))
		{
			/* Algorithm to select key byte based on offset. */
			uint16_t const key_offset = bitswap<10>(m_address, 10, 9, 5, 7, 6, 1, 3, 8, 2, 4) ^ 0x099;
			uint16_t const key_byte = m_ram[key_offset];

			/* And now for the full magic. */
			plaintext = decipher(key_byte, m_ciphertext);

			if (ACCESSING_BITS_16_31)
				plaintext <<= 16;
		}
	}

	return plaintext;
}


