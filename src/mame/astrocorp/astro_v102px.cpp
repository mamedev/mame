/***************************************************************************

    Astro Corp. V102PX custom CPU

    A 68000 with encrypted program ROMs.

    Each byte goes through one of 8 bitswap + xor combinations, chosen by
    3 address bits, then address bits 12-2 are scrambled. All the known
    chips use the same bitswap + xor combinations: they only differ in
    which address bits select them and in the address scrambling, which
    the driver selects with set_decryption().

    The device decrypts the region set with set_encrypted_region() into its
    own region. All the known programs also checksum the encrypted ROM at
    $800000 (it must sum to 0): the drivers map it there.

    The CPU Code key read by these games is unlikely to be inside this chip,
    so it's emulated separately (see astro_cpucode.cpp): the same V102PX
    model is found with different keys, and the same key with different
    V102PX models. Different runs of the same model with different keys
    can't be ruled out, though.

***************************************************************************/

