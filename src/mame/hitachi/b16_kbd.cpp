ioport_constructor b16_kbd_device::device_input_ports() const
{
	return INPUT_PORTS_NAME(b16_keyboard);
}

void b16_kbd_device::device_start()
{
	save_item(NAME(m_fifo));
	save_item(NAME(m_last_code));
	save_item(NAME(m_head));
	save_item(NAME(m_count));
	save_item(NAME(m_modifier_state));
	save_item(NAME(m_lock_pressed));
	save_item(NAME(m_lock_state));
}

void b16_kbd_device::device_reset()
{
	m_last_code = 0;
	m_head = m_count = 0;
	m_modifier_state = m_lock_pressed = m_lock_state = 0;
	m_irq_cb(0);
	reset_key_state();
	typematic_stop();
	start_processing(attotime::from_hz(16 * 120));
}

void b16_kbd_device::update_modifiers()
{
	u8 const modifiers = m_modifiers->read() & 0x3f;
	for (unsigned bit = 0; bit < 6; ++bit)
	{
		u8 const mask = 1U << bit;
		if ((modifiers ^ m_modifier_state) & mask)
		{
			m_modifier_state ^= mask;
			push(0x80 | (m_modifier_state & 0x03)
				| ((m_modifier_state & 0x0c) ? 0x04 : 0x00)
				| ((m_modifier_state & 0x30) ? 0x08 : 0x00));
		}
	}

	u8 const locks = m_lock_keys->read() & 0x03;
	u8 const pressed = locks & ~m_lock_pressed;
	m_lock_pressed = locks;
	for (unsigned bit = 0; bit < 2; ++bit)
	{
		if (BIT(pressed, bit))
		{
			m_lock_state ^= 1U << bit;
			push(0x90 | (BIT(m_lock_state, 0) ? 0x04 : 0x00)
				| (BIT(m_lock_state, 1) ? 0x02 : 0x00));
		}
	}
}

void b16_kbd_device::will_scan_row(u8 row)
{
	update_modifiers();
}

void b16_kbd_device::key_make(u8 row, u8 column)
{
	u8 const code = row * 8 + column;
	push(code);
	if (code != 0x71 && code != 0x73)
		typematic_start(row, column, attotime::from_msec(500), attotime::from_msec(60));
}

void b16_kbd_device::key_repeat(u8 row, u8 column)
{
	// A release can precede the next row scan; never repeat an already-up key.
	if (!BIT(m_key_rows[row]->read(), column))
	{
		typematic_stop();
		return;
	}
	update_modifiers();
	push(row * 8 + column);
}

void b16_kbd_device::data_w(u8 data)
{
	// B16 and EX-II POST send 10h and wait for an F0h-family status report.
	// F0h identifies the standard keyboard with no diagnostic errors.
	if (data == 0x10)
		push(0xf0);
}

void b16_kbd_device::push(u8 data)
{
	if (m_count == m_fifo.size())
	{
		logerror("Keyboard receive buffer full, dropping %02x\n", data);
		return;
	}
	m_fifo[(m_head + m_count) % m_fifo.size()] = data;
	if (!m_count++)
		m_irq_cb(1);
}

u8 b16_kbd_device::data_r()
{
	if (!m_count)
		return m_last_code;

	u8 const data = m_fifo[m_head];
	if (!machine().side_effects_disabled())
	{
		m_last_code = data;
		m_head = (m_head + 1) % m_fifo.size();
		--m_count;
		m_irq_cb(0);
		if (m_count)
			m_irq_cb(1);
	}
	return data;
}

u8 b16_kbd_device::status_r()
{
	// USART transmitter ready/empty, receiver ready while a byte is pending.
	return 0x05 | (m_count ? 0x02 : 0x00);
}
